def normalize_lang(lang_code: str | None) -> str:
    if not lang_code:
        return "ru"
    code = lang_code.lower().split("-")[0]
    return code if code in SUPPORTED_LANGS else "ru"


def get_catalog(lang_code: str) -> dict:
    lang = normalize_lang(lang_code)
    base = TRANSLATIONS["ru"].copy()
    base.update(TRANSLATIONS.get(lang, {}))
    return base
